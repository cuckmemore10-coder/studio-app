window.CaptionEngine = (function () {
  function pick(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
  }

  function intensityBucket(n) {
    if (n <= 33) return "low";
    if (n <= 66) return "mid";
    return "high";
  }

  function generate(opts) {
    const theme = opts.theme || "teasing";
    const perspective = opts.perspective || "none";
    const intensity = typeof opts.intensity === "number" ? opts.intensity : 50;
    const bank = window.CAPTION_BANK;
    const themeLines = (bank.themes[theme] && bank.themes[theme].lines) || bank.themes.teasing.lines;
    const mode = Math.random();

    let caption = "";
    if (mode < 0.35) {
      caption = pick(bank.standalone);
    } else if (mode < 0.7) {
      const prefix = pick(bank.perspectives[perspective] || bank.perspectives.none);
      const line = pick(themeLines);
      caption = prefix ? (prefix + " " + line) : line;
    } else {
      const line = pick(themeLines);
      const bump = pick(bank.intensifiers[intensityBucket(intensity)]);
      const closer = pick(bank.closers);
      caption = [line, bump, closer].filter(Boolean).join(" ");
    }

    // Light intensity tweak: append intensifier more often at high
    if (intensity > 75 && Math.random() < 0.4 && !caption.includes("Ruin")) {
      caption = caption + " " + pick(bank.intensifiers.high);
    }
    if (intensity < 25 && Math.random() < 0.3) {
      caption = caption + " " + pick(bank.intensifiers.low);
    }

    return caption.trim().replace(/\s+/g, " ");
  }

  function countTemplates() {
    const b = window.CAPTION_BANK;
    let n = b.standalone.length;
    Object.values(b.themes).forEach((t) => (n += t.lines.length));
    return n;
  }

  return { generate, countTemplates, pick };
})();
